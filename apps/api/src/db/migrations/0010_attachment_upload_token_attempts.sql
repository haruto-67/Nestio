-- sha256不一致等でバイト列検証に失敗した際、それまではトークン検証の直後（本文の読み込みより
-- 前）に即座に使用済みにしていたため、正しいファイルで直後に再試行してもトークンが既に消費
-- されておりリトライ不能になっていた（実機検証2026-08-22で判明）。
-- 「確定消費」はバイト列検証まで全て通過した後に行うよう変更し、それまでの間の再試行回数だけ
-- ここで制限する（改修17回目フォローアップ3）
ALTER TABLE attachment_upload_tokens ADD COLUMN attempt_count INTEGER NOT NULL DEFAULT 0;
